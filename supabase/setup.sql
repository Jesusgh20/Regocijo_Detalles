-- ── 1. Categorías ────────────────────────────────────────────────────
create table if not exists public.categorias (
  slug     text primary key check (slug ~ '^[a-z0-9-]{1,40}$'),
  label    text not null check (char_length(label) between 1 and 40),
  singular text check (singular is null or char_length(singular) <= 40),
  orden    integer not null default 0
);

-- ── 2. Ramos ─────────────────────────────────────────────────────────
create table if not exists public.ramos (
  id                  bigint generated by default as identity primary key,
  slug                text not null unique check (slug ~ '^[a-z0-9-]{1,80}$'),
  nombre              text not null check (char_length(nombre) between 1 and 120),
  categoria           text not null references public.categorias (slug) on update cascade on delete restrict,
  descripcion         text not null check (char_length(descripcion) between 1 and 2000),
  detalle             text check (detalle is null or char_length(detalle) <= 1000),
  incluye             jsonb not null default '[]'::jsonb,
  tamano_texto        text check (tamano_texto is null or char_length(tamano_texto) <= 20),
  precio_base         integer check (precio_base is null or (precio_base >= 0 and precio_base <= 100000000)),
  variantes_precio    jsonb not null default '[]'::jsonb,
  colores_disponibles text check (colores_disponibles is null or char_length(colores_disponibles) <= 300),
  extras_opcionales   jsonb not null default '[]'::jsonb,
  imagenes            jsonb not null default '[]'::jsonb,
  disponible          boolean not null default true,
  destacado           boolean not null default false,
  insignia            boolean not null default false,
  tags_busqueda       jsonb not null default '[]'::jsonb,
  publicado           boolean not null default true,   -- false = borrador (no se ve en el sitio)
  orden               integer not null default 0,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  -- todo ramo debe tener un precio: uno solo o varias opciones
  constraint ramos_tiene_precio check (precio_base is not null or jsonb_array_length(variantes_precio) > 0),
  constraint ramos_jsonb_son_listas check (
    jsonb_typeof(incluye) = 'array' and jsonb_typeof(variantes_precio) = 'array'
    and jsonb_typeof(extras_opcionales) = 'array' and jsonb_typeof(imagenes) = 'array'
    and jsonb_typeof(tags_busqueda) = 'array'
  )
);
create index if not exists ramos_categoria_idx on public.ramos (categoria);
create index if not exists ramos_orden_idx on public.ramos (orden, id);

create or replace function public.tocar_updated_at() returns trigger
language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists ramos_updated_at on public.ramos;
create trigger ramos_updated_at before update on public.ramos
  for each row execute function public.tocar_updated_at();

-- ── 3. Quién es administradora ───────────────────────────────────────
-- Lista de correos autorizados a editar. Nadie puede leerla por la API (RLS sin políticas).
create table if not exists public.admins (email text primary key);
alter table public.admins enable row level security;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select auth.uid() is not null
     and exists (
       select 1 from public.admins a
       where lower(a.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
     )
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- ── 4. Seguridad por filas (RLS): el público SOLO lee, la administradora escribe ──
alter table public.categorias enable row level security;
alter table public.ramos      enable row level security;

drop policy if exists "categorias: lectura pública" on public.categorias;
create policy "categorias: lectura pública" on public.categorias
  for select to anon, authenticated using (true);

drop policy if exists "categorias: la administradora escribe" on public.categorias;
create policy "categorias: la administradora escribe" on public.categorias
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "ramos: lectura pública de los publicados" on public.ramos;
create policy "ramos: lectura pública de los publicados" on public.ramos
  for select to anon, authenticated using (publicado = true or public.is_admin());

drop policy if exists "ramos: la administradora escribe" on public.ramos;
create policy "ramos: la administradora escribe" on public.ramos
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

grant usage on schema public to anon, authenticated;
grant select on public.categorias, public.ramos to anon, authenticated;
grant insert, update, delete on public.categorias, public.ramos to authenticated;
grant usage, select on sequence public.ramos_id_seq to authenticated;

-- ── 5. Almacenamiento de fotos ───────────────────────────────────────
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('ramos', 'ramos', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = true, file_size_limit = 5242880,
      allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];

drop policy if exists "fotos: la administradora sube" on storage.objects;
create policy "fotos: la administradora sube" on storage.objects
  for insert to authenticated with check (bucket_id = 'ramos' and public.is_admin());

drop policy if exists "fotos: la administradora edita" on storage.objects;
create policy "fotos: la administradora edita" on storage.objects
  for update to authenticated using (bucket_id = 'ramos' and public.is_admin())
  with check (bucket_id = 'ramos' and public.is_admin());

drop policy if exists "fotos: la administradora borra" on storage.objects;
create policy "fotos: la administradora borra" on storage.objects
  for delete to authenticated using (bucket_id = 'ramos' and public.is_admin());
